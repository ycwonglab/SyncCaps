"""synccaps_repair_report.py -- every seed-level contrast the v5 evidence-chain
repair plan asks for, regenerated from the committed result JSONs.

The plan requires that "every confidence interval can be regenerated by a
documented command". This is that command. It reads only `gating_results/*.json`
-- no checkpoints, no GPU -- so it can be re-run at any time to check that a
number quoted in the manuscript still matches the artifact it came from.

Clip-level and source-video-group-level inference live in `synccaps_mcnemar.py`,
which needs the per-clip prediction dumps. The two are complementary and answer
different nulls; see that file's header.

  python synccaps_repair_report.py                 # single view (the L3 grid protocol)
  python synccaps_repair_report.py --multiclip     # 3 clips x 1 crop
"""
import argparse
import json
import math
import os

# Default matches this release package. The original working tree kept these
# files in `gating_results/`; --results-dir accepts either.
RES = 'results/seed_summaries/raw_results_json'

# t critical values, two-sided 95% / 90%, indexed by degrees of freedom
T95 = {1: 12.706, 2: 4.303, 3: 3.182, 4: 2.776, 5: 2.571, 6: 2.447, 7: 2.365,
       8: 2.306}
T90 = {1: 6.314, 2: 2.920, 3: 2.353, 4: 2.132, 5: 2.015, 6: 1.943, 7: 1.895,
       8: 1.860}


def load(fname, arm, key='test_acc_certain'):
    """-> {seed: accuracy}. Missing file or arm is not an error: the report is
    meant to be readable while a batch is still filling the grid in."""
    p = os.path.join(RES, fname)
    if not os.path.exists(p):
        return {}
    d = json.load(open(p))
    if arm not in d or not isinstance(d[arm], list):
        return {}
    out = {}
    for r in d[arm]:
        if key in r:
            out[r['seed']] = r[key]
    return out


def merge(*dicts):
    """Union of per-seed maps. Later sources lose to earlier ones on collision,
    so the canonical file is always listed first."""
    out = {}
    for d in reversed(dicts):
        out.update(d)
    return out


def contrast(name, A, B, margin=None, note=''):
    """Paired seed-level difference A - B over the seeds both arms share."""
    seeds = sorted(set(A) & set(B))
    if len(seeds) < 2:
        print(f'  {name:<46} -- only {len(seeds)} shared seed(s), skipped')
        return None
    d = [A[s] - B[s] for s in seeds]
    n = len(d)
    m = sum(d) / n
    sd = math.sqrt(sum((x - m) ** 2 for x in d) / (n - 1))
    se = sd / math.sqrt(n) if sd else 0.0
    t95, t90 = T95.get(n - 1, 2.0), T90.get(n - 1, 1.7)
    lo, hi = m - t95 * se, m + t95 * se
    wins = sum(1 for x in d if x > 0)
    line = (f'  {name:<46} {m:+6.2f} +/- {sd:4.2f}  n={n}  '
            f'95% CI [{lo:+6.2f}, {hi:+6.2f}]  {wins}/{n}')
    if margin is not None:
        l90, h90 = m - t90 * se, m + t90 * se
        equiv = -margin < l90 and h90 < margin
        line += (f'\n  {"":<46} TOST +/-{margin:.1f}: 90% CI '
                 f'[{l90:+6.2f}, {h90:+6.2f}] -> '
                 f'{"EQUIVALENT" if equiv else "NOT shown equivalent"}')
    print(line)
    if note:
        print(f'  {"":<46} {note}')
    print(f'  {"":<46} per seed: ' +
          ', '.join(f'{s}:{x:+.2f}' for s, x in zip(seeds, d)))
    return m


def crossed_dictionaries(name, kind_a, kind_b, files, dicts=(0, 1, 2, 3),
                         key='test_acc_certain', margin=None, note='',
                         preloaded=None):
    """Crossed pair-dictionary contrast: within-dictionary first, then across.

    The pair-composition claim is about the DICTIONARY, not about an optimizer
    seed. Pairing at the seed level across dictionaries would be meaningless --
    seed 42 under pair_seed 1 shares nothing with seed 42 under pair_seed 2
    except the optimizer stream. So the contrast is formed inside each
    dictionary (mean over that dictionary's optimizer seeds), and the four
    resulting dictionary-level contrasts are then summarised with the same
    paired t-interval used everywhere else in this report. n is 4 dictionaries,
    not 12 runs, which is the honest unit of replication here.
    """
    # The pair_seed 0 MIXED arm has no dedicated results file -- it is the main
    # B4_gram cell, whose seeds are spread over two combined files and already
    # merged by the caller. `preloaded` supplies it rather than re-deriving it.
    preloaded = preloaded or {}

    def get(kind, d):
        if (kind, d) in preloaded:
            return preloaded[(kind, d)]
        return load(files(kind, d), 'B4_gram', key)

    per, used = [], []
    for d in dicts:
        A = get(kind_a, d)
        B = get(kind_b, d)
        seeds = sorted(set(A) & set(B))
        if not seeds:
            continue
        per.append(sum(A[s] for s in seeds) / len(seeds)
                   - sum(B[s] for s in seeds) / len(seeds))
        used.append((d, len(seeds)))
    if len(per) < 2:
        print(f'  {name:<46} -- only {len(per)} dictionary/ies, skipped')
        return None
    n = len(per)
    m = sum(per) / n
    sd = math.sqrt(sum((x - m) ** 2 for x in per) / (n - 1))
    se = sd / math.sqrt(n) if sd else 0.0
    t95, t90 = T95.get(n - 1, 2.0), T90.get(n - 1, 1.7)
    line = (f'  {name:<46} {m:+6.2f} +/- {sd:4.2f}  n={n} dicts  '
            f'95% CI [{m - t95 * se:+6.2f}, {m + t95 * se:+6.2f}]  '
            f'{sum(1 for x in per if x > 0)}/{n}')
    if margin is not None:
        l90, h90 = m - t90 * se, m + t90 * se
        line += (f'\n  {"":<46} TOST +/-{margin:.1f}: 90% CI '
                 f'[{l90:+6.2f}, {h90:+6.2f}] -> '
                 f'{"EQUIVALENT" if -margin < l90 and h90 < margin else "NOT shown equivalent"}')
    print(line)
    if note:
        print(f'  {"":<46} {note}')
    print(f'  {"":<46} per dictionary: ' +
          ', '.join(f'pair{d}:{x:+.2f}' for (d, _), x in zip(used, per)))
    print(f'  {"":<46} optimizer seeds per dictionary: ' +
          ', '.join(f'pair{d}:n={k}' for d, k in used))
    return m


def head(t):
    print('\n' + '=' * 96 + f'\n{t}\n' + '=' * 96)


if __name__ == '__main__':
    ap = argparse.ArgumentParser()
    ap.add_argument('--multiclip', action='store_true',
                    help='read the 3-clip re-scoring instead of single view. '
                         'NEVER mix the two in one contrast (ledger trap).')
    ap.add_argument('--margin', type=float, default=1.0,
                    help='pre-specified equivalence margin, accuracy points')
    ap.add_argument('--results-dir', default=RES,
                    help='directory of committed result JSONs')
    args = ap.parse_args()
    RES = args.results_dir

    if args.multiclip:
        MC = 'multiclip_ucf101_resnet_ptfz_official1_noval_fc.json'
        MCV = 'multiclip_ucf101_resnet_ptfz_official1_fc.json'
        K = 'test_acc_certain_mv'
        L = lambda arm: load(MC, arm, K)
        LV = lambda arm: load(MCV, arm, K)
        proto = '3 clips x 1 crop'
    else:
        FC = 'synccaps_ucf101_resnet_ptfz_official1_noval_fc'
        K = 'test_acc_certain'
        L = lambda arm: merge(
            load(f'{FC}_{arm}.json', arm, K),
            load(f'{FC}_B0_linear-B4_syncnorm-B4_gram-CB_tsketch.json', arm, K),
            load(f'{FC}_B4_gram-CB_tsketch.json', arm, K))
        LV = lambda arm: load(
            'synccaps_ucf101_resnet_ptfz_official1_fc_'
            'B0_linear-B4_syncnorm-B4_gram.json', arm, K)
        proto = 'single view'

    print(f'SyncCaps evidence-chain repair report -- {proto}, `{K}`')
    print('Frozen ResNet-18 layer3, UCF101 official split-1, corrected '
          '(eval-mode) frozen BatchNorm throughout.')

    b0, b1, b4, gram = L('B0_linear'), L('B1_sync'), L('B4_syncnorm'), L('B4_gram')
    tsk, route, shuf = L('CB_tsketch'), L('R3_route'), L('B3_shuffle')

    head('Arm means')
    for nm, a in [('B0_linear', b0), ('B1_sync', b1), ('B4_syncnorm', b4),
                  ('B4_gram', gram), ('CB_tsketch', tsk), ('R3_route', route),
                  ('B3_shuffle', shuf)]:
        if a:
            v = list(a.values())
            m = sum(v) / len(v)
            sd = (math.sqrt(sum((x - m) ** 2 for x in v) / (len(v) - 1))
                  if len(v) > 1 else 0.0)
            print(f'  {nm:<16} {m:6.2f} +/- {sd:4.2f}  n={len(v)}  '
                  f'seeds {sorted(a)}')

    head('1. Method decomposition (restated Table 5.1 row)')
    contrast('sync statistic       B1 - B0', b1, b0)
    contrast('normalisation        B4 - B1', b4, b1)
    contrast('full method          B4 - B0', b4, b0)

    head('2. rho = 0 mechanism control (repair plan section 3)')
    contrast('B4_gram - B4_syncnorm', gram, b4, margin=args.margin,
             note='pre-correction values were +0.14 single / +0.27 multi-clip')

    head('3. Shuffle control, corrected BN (repair plan section 4)')
    contrast('B1_sync - B3_shuffle', b1, shuf, margin=args.margin,
             note='published -0.40 came from a PRE-FIX UNCACHED frozen run')

    head('4. Operator: exact sampled pairs vs Tensor Sketch (plan section 5.2)')
    contrast('B4_gram - CB_tsketch  (all seeds)', gram, tsk)
    fresh = {s: v for s, v in gram.items() if s in (5, 11, 23)}
    freshT = {s: v for s, v in tsk.items() if s in (5, 11, 23)}
    contrast('B4_gram - CB_tsketch  (fresh {5,11,23} only)', fresh, freshT,
             note='pre-registered confirmatory set, analysed separately from '
                  'the sequentially-extended n=6')
    C = 'synccaps_ucf101_clip_b32_ptfz_official1_noval_fc'
    cg = merge(load(f'{C}_B4_gram-CB_tsketch.json', 'B4_gram', 'test_acc_certain'),
               load(f'{C}_B4_gram-CB_tsketch-LR_bilinear.json', 'B4_gram',
                    'test_acc_certain'))
    ct = merge(load(f'{C}_B4_gram-CB_tsketch.json', 'CB_tsketch', 'test_acc_certain'),
               load(f'{C}_B4_gram-CB_tsketch-LR_bilinear.json', 'CB_tsketch',
                    'test_acc_certain'))
    if not args.multiclip:
        contrast('CLIP: B4_gram - CB_tsketch', cg, ct)
        sh = sorted(set(gram) & set(tsk) & set(cg) & set(ct))
        if len(sh) >= 2:
            iA = {s: gram[s] - tsk[s] for s in sh}
            iB = {s: cg[s] - ct[s] for s in sh}
            contrast('INTERACTION (Exact-Sketch): L3 - CLIP', iA, iB,
                     note='seed-matched; the backbone x operator term the plan '
                          'requires before any general superiority claim')

    head('5. Routing (repair plan section 5.1)')
    contrast('R3_route - B4_gram', route, gram, margin=args.margin,
             note='"parity" needs this TOST to pass; a sign flip is not a test')
    contrast('R3_route - B4_syncnorm', route, b4, margin=args.margin)
    contrast('R3_route - B0_linear', route, b0)

    head('6. Self-pairs vs cross-pairs (repair plan section 7)')
    SF = 'synccaps_ucf101_resnet_ptfz_official1_noval_fc'
    selfo = load(f'{SF}_nself2048_B4_gram.json', 'B4_gram', 'test_acc_certain')
    cross = load(f'{SF}_nself0_xself_B4_gram.json', 'B4_gram', 'test_acc_certain')
    if args.multiclip and (selfo or cross):
        print('  (self/cross arms are single-view only by design -- '
              'multiclip_eval cannot build an n_self != 64 model)')
    for nm, a in [('self-only  (n_self=2048)', selfo),
                  ('cross-only (n_self=0)', cross)]:
        if a:
            v = list(a.values())
            print(f'  {nm:<28} {sum(v)/len(v):6.2f}  n={len(v)}')
    contrast('cross-only - self-only', cross, selfo,
             note='cross > self supports the co-activation reading; a tie means '
                  'the gain is normalized activation ENERGY, not synchrony')
    contrast('mixed(64) - self-only', gram, selfo)
    contrast('mixed(64) - cross-only', gram, cross)
    contrast('self-only - B0_linear', selfo, b0,
             note='how much of the +5.84 full-method gain survives with NO '
                  'cross terms at all')

    head('6b. Crossed FOUR-dictionary pair composition (repair plan section 7)')
    print('  Section 6 above is pair_seed 0 only. The manuscript reports the')
    print('  CROSSED summary over four independent pair dictionaries; that is')
    print('  this section. Dictionaries: pair_seed 0, 1, 2, 3 (see')
    print('  pair_indices/PAIR_INDICES_MANIFEST.json).')
    print()

    def pcfile(kind, d):
        suffix = '' if d == 0 else f'_pair{d}'
        stem = {'mixed': '', 'cross': '_nself0_xself', 'self': '_nself2048'}[kind]
        return f'{SF}{stem}{suffix}_B4_gram.json'

    if args.multiclip:
        print('  (single-view only by design -- multiclip_eval cannot build an '
              'n_self != 64 model)')
    crossed_dictionaries('cross-only - self-only  [4 dicts]', 'cross', 'self',
                         pcfile,
                         note='the co-activation reading: cross-pair terms carry '
                              'the gain, not self-pair activation energy')
    crossed_dictionaries('mixed(64) - cross-only  [4 dicts]', 'mixed', 'cross',
                         pcfile, margin=args.margin, preloaded={('mixed', 0): gram},
                         note='adding 64 self-pairs to a cross-only dictionary '
                              'buys nothing')

    head('7. Val-carved replication, corrected frozen arms (plan section 2.1)')
    # PROTOCOL TRAP: the fine-tuned partner for a VAL-CARVED frozen arm must
    # itself be val-carved. `multiclip_..._pt_official1_noval.json` is the NOVAL
    # fine-tuned file, and pairing it with val-carved frozen arms would mix two
    # training protocols inside one contrast. There is no val-carved fine-tuned
    # multi-clip file yet, so in --multiclip mode these contrasts correctly
    # report "0 shared seeds" and skip rather than silently mismatching.
    FT = ('multiclip_ucf101_resnet_pt_official1.json' if args.multiclip
          else 'synccaps_ucf101_resnet_pt_official1_B0_linear-B4_syncnorm.json')
    ftk = 'test_acc_certain_mv' if args.multiclip else 'test_acc_certain'
    ft0, ft4 = load(FT, 'B0_linear', ftk), load(FT, 'B4_syncnorm', ftk)
    v0, v4, vg = LV('B0_linear'), LV('B4_syncnorm'), LV('B4_gram')
    for nm, a in [('frozen B0', v0), ('frozen B4', v4), ('frozen B4_gram', vg),
                  ('fine-tuned B0', ft0), ('fine-tuned B4', ft4)]:
        if a:
            v = list(a.values())
            print(f'  {nm:<28} {sum(v)/len(v):6.2f}  n={len(v)}')
    contrast('readout on frozen features B4 - B0', v4, v0)
    contrast('HEADLINE frozen B4 - fine-tuned B0', v4, ft0)
    contrast('fine-tuning ON TOP  ftB4 - frozen B4', ft4, v4, margin=args.margin)
    contrast('fine-tuning helps linear  ftB0 - frB0', ft0, v0)
    contrast('val-carved rho=0  B4_gram - B4', vg, v4, margin=args.margin)

    print('\nNOTE: single-view and multi-clip numbers are never mixed in one '
          'contrast (ledger trap #4 / plan section 4).')
